-- ============================================================================
--  Постоянный порядок команд в игре.
--
--  Цвет команды на табло закреплён за её номером в игре. Ведущий вносит
--  команды одним списком — в одной транзакции, а now() в транзакции одно и
--  то же, и порядок команд с одинаковым временем был бы случайным: цвета
--  перескакивали бы между обновлениями табло. clock_timestamp() даёт каждой
--  строке своё время — порядок совпадает с порядком в списке ведущего.
-- ============================================================================

alter table players alter column created_at set default clock_timestamp();
