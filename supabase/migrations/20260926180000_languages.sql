-- ============================================================================
--  Языки: английский, испанский, португальский, русский.
--
--  games.language — язык игры. Ведущий выбирает его при создании (по
--  умолчанию — свой язык сайта), и все участники видят игру на нём, пока
--  сами не выберут другой язык в меню.
--
--  Новости команде (notices) и записи журнала денег (ledger) сервер пишет
--  не готовой фразой, а кодом с подробностями (params): сайт собирает фразу
--  на языке читателя. message и reason остаются — английский текст для
--  старых записей и для причин, которые ведущий пишет сам (штраф, грант).
-- ============================================================================

alter table games add column language text not null default 'en'
  check (language in ('en', 'es', 'pt', 'ru'));

alter table notices add column params jsonb;
alter table ledger add column params jsonb;
